// Test workers do not inherit Gradle's network JVM properties. Forward explicitly
// supplied proxy/truststore settings without weakening certificate validation.
tasks.withType<Test>().configureEach {
    maxHeapSize = "2g"
    systemProperty("robolectric.dependency.repo.url", "https://repo.maven.apache.org/maven2")
    listOf("http.proxyHost", "http.proxyPort", "https.proxyHost", "https.proxyPort", "javax.net.ssl.trustStore").forEach { key ->
        System.getProperty(key)?.let { systemProperty(key, it) }
    }
    System.getProperty("https.proxyHost")?.let { systemProperty("robolectric.dependency.proxy.host", it) }
    System.getProperty("https.proxyPort")?.let { systemProperty("robolectric.dependency.proxy.port", it) }
    val testHome = gradle.gradleUserHomeDir.resolve("robolectric-home")
    systemProperty("user.home", testHome.absolutePath)
    doFirst { testHome.mkdirs() }
}
